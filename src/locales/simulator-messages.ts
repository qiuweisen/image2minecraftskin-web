export function getSimulatorDictionary(
  locale: import('@/lib/locale').Locale
): Dictionary {
  return Object.fromEntries(
    (Object.keys(en) as Array<keyof Dictionary>).map((key) => [
      key,
      generatedMessages[key]({}, { locale }),
    ])
  ) as Dictionary;
}
